/**
 * lib/disclaimer.ts
 * The company disclaimer on every FINVA answer that touches advice (insurance,
 * investments, tax, planning). Appended in code, not left to the model, so it
 * is always there and always worded the same. Plain admin answers (schedule,
 * tasks, emails) are left alone.
 */

const MARK = 'Disclaimer:';

export const DISCLAIMER =
  `${MARK} This answer is general information generated by FINVA for the internal use of the company's licensed advisors. ` +
  'It is not personalised advice or a recommendation to any client. Any recommendation must go through the company\'s ' +
  'fact-find, suitability assessment and compliance process, and figures such as premiums, yields, returns and tax ' +
  'are estimates to be confirmed against the official product documents. The company accepts no liability for decisions ' +
  'made solely on the basis of this answer.';

const ADVICE_WORDS =
  /\b(insur\w*|takaful|premium\w*|polic(?:y|ies)|medical|coverage|sum assured|critical illness|tpd|coi|ilp|riders?|claims?|fund\w*|unit trust|invest\w*|bonds?|sukuk|fcns?|structured|notes?|portfolio\w*|allocat\w*|retire\w*|stocks?|shares|equit\w*|etfs?|reits?|tax\w*|yields?|coupons?|returns?|epf|prs|annuit\w*|loan|mortgage|issuer\w*|ratings?|strike|knock\w*|repric\w*|mediasas)\b/i;

/** True when the question or the answer is about advice rather than admin. */
export function isAdviceAnswer(question: string, answer: string): boolean {
  return ADVICE_WORDS.test(question) || ADVICE_WORDS.test(answer);
}

/** Adds the disclaimer once, at the bottom, under a divider. */
export function withDisclaimer(question: string, answer: string): string {
  if (!answer || answer.includes(MARK) || !isAdviceAnswer(question, answer)) return answer;
  return `${answer.trimEnd()}\n\n---\n*${DISCLAIMER}*`;
}

/** Removes it again before an earlier answer is sent back to the model as history. */
export function stripDisclaimer(text: string): string {
  const i = text.indexOf(`\n\n---\n*${MARK}`);
  return i >= 0 ? text.slice(0, i) : text;
}
